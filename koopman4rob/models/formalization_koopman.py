import torch
import torch.nn as nn
import torch.nn.functional as F


def get_activation(name: str):
    return {
        "relu": nn.ReLU(),
        "sigmoid": nn.Sigmoid(),
        "tanh": nn.Tanh(),
        "swish": nn.SiLU(),
        "elu": nn.ELU(),
        "mish": nn.Mish(),
        "linear": nn.Identity(),
    }[name]


class Encoder(nn.Module):
    """
    Represents the lifting function psi(x).
    Maintains architecture of original training Encoder for strict weight compatibility.
    """

    def __init__(
        self,
        state_dim,
        action_dim,
        hidden_sizes,
        lifted_dim,
        activation,
        include_iden_state=True,
    ):
        super().__init__()
        self.state_dim = state_dim
        self.lifted_dim = lifted_dim
        self.include_iden_state = include_iden_state

        # Neural feature dim = lifted_dim - state_dim (if identity is included)
        self.output_size = lifted_dim - state_dim if include_iden_state else lifted_dim

        layers = []
        # Recreating the exact Sequential structure from training
        self.sizes = [self.state_dim] + hidden_sizes + [self.output_size]
        last_i = len(self.sizes) - 2
        not_linear = activation != "linear"

        for i, (in_dim, out_dim) in enumerate(zip(self.sizes[:-1], self.sizes[1:])):
            layers.append(nn.Linear(in_dim, out_dim, bias=(not_linear or i == last_i)))
            if not_linear and i != last_i:
                layers.append(get_activation(activation))

        self.layers = nn.Sequential(*layers)

    def forward(self, x):
        """Standard forward pass for compatibility."""
        encoded = self.layers(x)
        if self.include_iden_state:
            return torch.cat([x, encoded], dim=1)
        return encoded

    def psi(self, x):
        """Formal alias for the lifting map x -> z."""
        return self.forward(x)


class Decoder(nn.Module):
    """
    Represents the projection C.
    Maintains architecture of original training Decoder for strict weight compatibility.
    """

    def __init__(
        self,
        state_dim,
        action_dim,
        hidden_sizes,
        lifted_dim,
        activation,
        include_iden_state=True,
        iden_decoder=True,
    ):
        super().__init__()
        self.state_dim = state_dim
        self.lifted_dim = lifted_dim
        self.iden_decoder = iden_decoder
        self.include_iden_state = include_iden_state

        if not self.iden_decoder:
            layers = []
            self.sizes = [self.lifted_dim] + hidden_sizes + [state_dim]
            last_i = len(self.sizes) - 2
            not_linear = activation != "linear"
            for i, (in_dim, out_dim) in enumerate(zip(self.sizes[:-1], self.sizes[1:])):
                layers.append(
                    nn.Linear(in_dim, out_dim, bias=(not_linear or i == last_i))
                )
                if not_linear and i != last_i:
                    layers.append(get_activation(activation))
            self.layers = nn.Sequential(*layers)

    def forward(self, z):
        if self.include_iden_state and self.iden_decoder:
            # Identity decoding: C = [I, 0]
            return z[:, : self.state_dim]
        else:
            return self.layers(z)


class KoopmanAnalyzer(nn.Module):
    """
    A lightweight wrapper for analyzing the trained Koopman Operator.
    Focuses on Evaluation, Spectral Analysis, and Closed-Form Refinement.
    """

    def __init__(
        self,
        state_dim,
        action_dim,
        hidden_sizes,
        lifted_dim,
        activation="relu",
        include_iden_state=True,
        iden_decoder=True,
    ):
        super().__init__()
        self.state_dim = state_dim
        self.action_dim = action_dim
        self.lifted_dim = lifted_dim
        self.include_iden_state = include_iden_state

        # 1. Initialize Modules (Architecture matches training exactly)
        self.encoder = Encoder(
            state_dim,
            action_dim,
            hidden_sizes,
            lifted_dim,
            activation,
            include_iden_state,
        )
        self.decoder = Decoder(
            state_dim,
            action_dim,
            hidden_sizes,
            lifted_dim,
            activation,
            include_iden_state,
            iden_decoder,
        )

        # 2. Initialize Matrices (Placeholder, will be loaded)
        self.register_buffer("A", torch.zeros(lifted_dim, lifted_dim))
        self.register_buffer("B", torch.zeros(lifted_dim, action_dim))

        self.eval()  # Default to eval mode

    def load_pretrained(self, model_dir, device="cpu"):
        """
        Loads weights from the split .pth files generated by the training script.
        """
        try:
            self.encoder.load_state_dict(
                torch.load(f"{model_dir}/encoder.pth", map_location=device)
            )

            # Load A and B. Note: Training script saved them as raw tensors, not state_dicts.
            A_data = torch.load(f"{model_dir}/A.pth", map_location=device)
            B_data = torch.load(f"{model_dir}/B.pth", map_location=device)
            self.A.data = A_data
            self.B.data = B_data

            if not self.decoder.iden_decoder:
                self.decoder.load_state_dict(
                    torch.load(f"{model_dir}/decoder.pth", map_location=device)
                )

            self.to(device)
            print(f"[INFO] Analysis model successfully loaded from {model_dir}")
        except FileNotFoundError as e:
            print(f"[ERROR] Failed to load model: {e}")

    # =========================================================
    #  Formal Analysis Methods
    # =========================================================

    def psi(self, x: torch.Tensor) -> torch.Tensor:
        """Formal lifting function z = psi(x)."""
        return self.encoder.psi(x)

    def linear_forward(self, z: torch.Tensor, u: torch.Tensor) -> torch.Tensor:
        """
        Evolve state in feature space: z_{t+1} = z_t * A^T + u_t * B^T
        (Corresponds to z_{t+1} = A z_t + B u_t in column vector notation)
        """
        return F.linear(z, self.A) + F.linear(u, self.B)

    def predict(self, x: torch.Tensor, u: torch.Tensor) -> torch.Tensor:
        """Full trajectory: x -> z -> z' -> x'"""
        z = self.psi(x)
        z_next = self.linear_forward(z, u)
        return self.decoder(z_next)

    def compute_exact_operator(self, x_data, u_data, x_next_data, regularizer=1e-6):
        """
        Refines K (A and B) using the closed-form EDMD solution on the provided dataset.
        Solves: K = G^+ A

        Args:
            x_data, u_data, x_next_data: Tensors (Batch, Dim)
        """
        with torch.no_grad():
            # 1. Lift the data
            Z = self.psi(x_data)  # Psi_m
            Z_prime = self.psi(x_next_data)  # Psi_{m+1}
            U = u_data

            # 2. Form the input matrix for regression: Omega = [Z, U]
            # We are solving for linear map M such that: Z_prime ~ [Z, U] * M^T
            Omega = torch.cat([Z, U], dim=1)

            # 3. Compute Matrices G and A (as per your LaTeX prompt)
            # G = (1/M) * Sum (Psi_m* Psi_m) -> Omega.T @ Omega
            # A_stat = (1/M) * Sum (Psi_m* Psi_{m+1}) -> Omega.T @ Z_prime

            M = Omega.shape[0]
            G_mat = (Omega.T @ Omega) / M
            A_mat = (Omega.T @ Z_prime) / M

            # 4. Truncated SVD / Pseudoinverse to solve K = G_dagger * A
            # Add small ridge regularization for stability before inversion
            G_mat_reg = G_mat + regularizer * torch.eye(
                G_mat.shape[0], device=G_mat.device
            )

            # K_full contains both A and B. shape: (lifted+action, lifted)
            K_full = torch.linalg.pinv(G_mat_reg) @ A_mat

            # 5. Extract A and B
            # Note: PyTorch Linear layer weights are stored as (Out, In).
            # Our regression solved for X * K_full = Y -> so K_full is (In, Out).
            # We need to transpose them to store in self.A/B.

            A_new_T = K_full[: self.lifted_dim, :]
            B_new_T = K_full[self.lifted_dim :, :]

            self.A.data = A_new_T.T
            self.B.data = B_new_T.T

            print("[INFO] Matrices A and B refined using closed-form EDMD.")
            return G_mat, A_mat

    def analyze_stability(self):
        """
        Performs spectral analysis on Matrix A.
        Returns:
            eigenvalues: Complex eigenvalues
            max_radius: Spectral radius (should be <= 1 for stability)
        """
        # Compute eigenvalues of A
        evals = torch.linalg.eigvals(self.A)
        max_radius = torch.max(torch.abs(evals)).item()

        print(f"[INFO] Spectral Radius: {max_radius:.4f}")
        if max_radius > 1.0:
            print("[WARN] System is potentially UNSTABLE (Radius > 1.0)")
        else:
            print("[INFO] System is STABLE (Radius <= 1.0)")

        return evals, max_radius
